import { execFileSync } from 'node:child_process';
import { mkdtempSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import assert from 'node:assert/strict';
import { test } from 'node:test';
import { main } from './run.mjs';

const scenario = 'AC-1: Complete mock stream';
const change = 'verify-mock-stream-completion';
const request = 'Verify mock stream completion.';
const specification = {
  goal: 'Detect incomplete mock runs.',
  work: 'Add a smoke check that requires a matching RUN_FINISHED event.',
  scenarios: [
    { name: scenario, when: 'the requested run starts and finishes', then: 'the check exits successfully' },
    {
      name: 'AC-2: Truncated mock stream',
      when: 'the response ends after TEXT_MESSAGE_END',
      then: 'the check exits unsuccessfully and reports missing RUN_FINISHED',
    },
  ],
};

function git(cwd, ...args) {
  return execFileSync('git', args, { cwd, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim();
}

function setup(t) {
  mkdirSync('.factory/test-runs', { recursive: true });
  const cwd = mkdtempSync(join(process.cwd(), '.factory', 'test-runs', 'repo-'));
  git(cwd, 'init', '-q');
  git(cwd, 'config', 'user.name', 'Factory Test');
  git(cwd, 'config', 'user.email', 'factory-test@example.invalid');
  writeFileSync(join(cwd, '.gitignore'), '/.factory/\n');
  writeFileSync(join(cwd, 'app.txt'), 'base\n');
  git(cwd, 'add', '.');
  git(cwd, 'commit', '-qm', 'Base');
  const base = git(cwd, 'rev-parse', 'HEAD');
  t.diagnostic(`Evidence retained in ${cwd}`);
  return { cwd, base };
}

for (const [label, verdicts, expectedStatus, expectedCode] of [
  ['first-pass success', ['pass'], 'passed', 0],
  ['one successful repair', ['defect', 'pass'], 'passed', 0],
  ['second defect', ['defect', 'defect'], 'rejected', 2],
  ['verification blocked', ['blocked'], 'blocked', 1],
  ['retry after implementation was blocked', [], 'blocked', 1],
]) {
  test(label, (t) => {
    const { cwd, base } = setup(t);
    let runPath;
    let repairCalls = 0;
    let verifierCalls = 0;
    let retrying = false;
    const verifierPaths = new Set();
    const codex = ({ cwd: tree, prompt, output, log, windowsSandbox }) => {
      assert.equal(windowsSandbox, retrying ? 'mxc' : undefined);
      writeFileSync(log, prompt);
      if (prompt.startsWith('Draft')) {
        runPath = join(tree, '..');
        writeFileSync(output, JSON.stringify(specification));
      } else if (prompt.startsWith('Independently verify')) {
        assert.ok(!verifierPaths.has(tree));
        verifierPaths.add(tree);
        const candidate = git(tree, 'rev-parse', 'HEAD');
        assert.ok(prompt.includes(candidate));
        const status = retrying ? 'pass' : verdicts[verifierCalls];
        verifierCalls++;
        assert.ok(status, 'Unexpected extra verifier call');
        writeFileSync(join(tree, 'temporary-fixture.txt'), 'Generated by the verifier\n');
        const evidence = (name, outcome, exitCode) => ({
          name, outcome, command: 'controlled fixture', exitCode, observed: 'controlled outcome',
        });
        const scenarios = status === 'blocked' ? [] : [
          evidence(scenario, status === 'pass' ? 'pass' : 'fail', status === 'pass' ? 0 : 1),
          evidence('AC-2: Truncated mock stream', 'pass', 1),
        ];
        writeFileSync(output, JSON.stringify({ status, summary: status, scenarios }));
      } else {
        if (repairCalls > 0 && !retrying) assert.match(prompt, /Repair the verified defects/);
        if (!verdicts.length && !retrying) {
          repairCalls++;
          writeFileSync(output, JSON.stringify({ status: 'blocked', summary: 'Tool unavailable' }));
          return;
        }
        writeFileSync(join(tree, 'app.txt'), `implementation ${++repairCalls}\n`);
        writeFileSync(output, JSON.stringify({ status: 'ready', summary: 'Ready for verification' }));
      }
    };
    const run = (...args) => main(args, { cwd, codex });
    if (label === 'first-pass success') {
      assert.throws(() => run('plan', '--request', request), /Provide --change/);
      assert.throws(() => run('plan', '--change', '../invalid', '--request', request), /kebab-case change ID/);
    }
    assert.equal(run('plan', '--change', change, '--request', request), 0);
    const state = () => JSON.parse(readFileSync(join(runPath, 'run.json'), 'utf8'));
    const { runId, draftRevision, specPath } = state();
    assert.equal(state().status, 'awaiting-approval');
    assert.equal(repairCalls, 0);
    const approve = (...args) => run('approve', '--run', runId, ...args);
    const draft = join(runPath, 'draft');
    const spec = join(draft, specPath);
    const markdown = readFileSync(spec, 'utf8');
    assert.equal(specPath, `specs/${change}.md`);
    assert.deepEqual(state().scenarios, specification.scenarios.map(({ name }) => name));
    if (label === 'first-pass success') {
      writeFileSync(spec, markdown.replace('- Then: the check exits successfully', '- Then:'));
      assert.throws(() => approve(), /nonempty When and Then/);
      writeFileSync(spec, markdown.replace('AC-2: Truncated mock stream', scenario));
      assert.throws(() => approve(), /unique name/);
      writeFileSync(spec, markdown);
      const app = join(draft, 'app.txt');
      const original = readFileSync(app);
      writeFileSync(app, 'unexpected code change\n');
      assert.throws(() => approve(), /may change only its specification/);
      writeFileSync(app, original);
      writeFileSync(spec, markdown.replace(specification.work, specification.work + '\n\nReview edit.'));
      assert.throws(() => approve('--revision', draftRevision), /does not match the specified revision/);
      assert.equal(state().draftRevision, draftRevision);
    }
    const approvalArgs = label === 'one successful repair' ? ['--revision', draftRevision] : [];
    assert.equal(repairCalls, 0);
    assert.equal(approve(...approvalArgs), expectedCode);
    assert.equal(state().approvedRevision, state().draftRevision);
    if (label === 'first-pass success') {
      assert.notEqual(state().approvedRevision, draftRevision);
      assert.match(git(draft, 'show', `${state().approvedRevision}:${specPath}`), /Review edit\./);
    }
    assert.equal(state().status, expectedStatus);
    assert.equal(state().attempts.length, verdicts.length || 1);
    assert.equal(repairCalls, verdicts.length || 1);
    assert.equal(verifierCalls, verdicts.length);
    assert.deepEqual(state().attempts.map((attempt) => attempt.status), verdicts.length ? verdicts : ['blocked']);
    assert.equal(new Set(state().attempts.flatMap((attempt) => attempt.candidate ?? [])).size, verdicts.length);
    if (expectedStatus === 'blocked') {
      const blocked = state();
      retrying = true;
      assert.equal(run('retry', '--run', runId, '--windows-sandbox', 'mxc'), 0);
      const retried = state();
      assert.equal(retried.status, 'passed');
      assert.equal(retried.approvedRevision, blocked.approvedRevision);
      assert.equal(retried.error, undefined);
      assert.deepEqual(retried.attempts[0], blocked.attempts[0]);
      assert.equal(retried.attempts[1].attempt, 1);
      assert.match(retried.attempts[1].log, /retry-1/);
      if (verdicts.length) {
        assert.equal(repairCalls, 1);
        assert.equal(retried.attempts[1].candidate, blocked.attempts[0].candidate);
        assert.equal(retried.attempts[1].implementationLog, undefined);
      } else {
        assert.equal(repairCalls, 2);
        assert.match(retried.attempts[1].implementationLog, /retry-1/);
      }
      assert.equal(verifierCalls, verdicts.length + 1);
    }
    assert.equal(git(cwd, 'rev-parse', 'HEAD'), base);
    assert.equal(git(cwd, 'status', '--porcelain'), '');
  });
}

test('approves a draft created by the previous factory format', (t) => {
  const { cwd, base } = setup(t);
  const runId = '81bb589d-4fbd-4e73-91c1-4d39985f3453';
  const runPath = join(cwd, '.factory', 'runs', runId);
  const draft = join(runPath, 'draft');
  mkdirSync(runPath, { recursive: true });
  git(cwd, 'worktree', 'add', '--detach', draft, base);
  const legacy = join(draft, 'openspec', 'changes', change);
  const specs = join(legacy, 'specs', 'mock-stream');
  mkdirSync(specs, { recursive: true });
  for (const file of ['proposal.md', 'design.md', 'tasks.md']) {
    writeFileSync(join(legacy, file), '# Draft\n');
  }
  writeFileSync(join(specs, 'spec.md'), `#### Scenario: ${scenario}\n- **WHEN** a run starts\n- **THEN** it finishes\n`);
  const statePath = join(runPath, 'run.json');
  writeFileSync(statePath, JSON.stringify({ runId, change, base, status: 'draft', attempts: [] }));
  const codex = ({ prompt, output }) => {
    assert.ok(prompt.includes(`openspec/changes/${change}`));
    writeFileSync(output, JSON.stringify({ status: 'blocked', summary: 'Controlled stop after approval' }));
  };
  assert.equal(main(['approve', '--run', runId], { cwd, codex }), 1);
  const state = JSON.parse(readFileSync(statePath, 'utf8'));
  assert.deepEqual(state.scenarios, [scenario]);
  assert.equal(state.approvedRevision, git(draft, 'rev-parse', 'HEAD'));
  assert.equal(state.error, 'Controlled stop after approval');
});
